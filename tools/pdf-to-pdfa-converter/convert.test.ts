import { openPdfDocument } from "@workspace/pdf-reader/document"
import { afterEach, describe, expect, it, vi } from "vitest"

import { convertPdf } from "./convert"
import { runEngine } from "./engine/run"
import { validateArchive } from "./validate"

vi.mock("@workspace/pdf-reader/document", () => ({ openPdfDocument: vi.fn() }))
vi.mock("./engine/run", () => ({ runEngine: vi.fn() }))
vi.mock("./validate", () => ({ validateArchive: vi.fn() }))

const open = vi.mocked(openPdfDocument)
const convert = vi.mocked(runEngine)
const check = vi.mocked(validateArchive)
const source = new File(["pdf"], "source.pdf", { type: "application/pdf" })

const options = () => ({
  profile: 2 as const,
  signal: new AbortController().signal,
  onProgress: vi.fn(),
})

function loading(promise: Promise<unknown>) {
  return {
    promise,
    destroy: vi.fn().mockResolvedValue(undefined),
  } as unknown as ReturnType<typeof openPdfDocument>
}

function documentWith(info = {}) {
  return { numPages: 2, getMetadata: vi.fn().mockResolvedValue({ info }) }
}

afterEach(() => {
  vi.resetAllMocks()
})

describe("PDF/A conversion", () => {
  it("makes the generated bytes available after checking the reopened copy", async () => {
    const original = documentWith()
    const copy = documentWith()
    const originalTask = loading(Promise.resolve(original))
    const copyTask = loading(Promise.resolve(copy))
    open.mockReturnValueOnce(originalTask).mockReturnValueOnce(copyTask)
    const bytes = new Uint8Array([37, 80, 68, 70]).buffer
    convert.mockResolvedValue({
      status: "ready",
      bytes,
      fontEncodingChanged: false,
    })
    check.mockResolvedValue("ready")

    const settings = options()
    const result = await convertPdf(source, settings)
    expect(result.status).toBe("ready")
    if (result.status === "ready") {
      expect(await result.blob.arrayBuffer()).toEqual(bytes)
    }
    expect(settings.onProgress.mock.calls.flat()).toEqual([
      "converting",
      "checking",
    ])
    expect(check).toHaveBeenCalledWith(original, copy, {
      profile: 2,
      fontEncodingChanged: false,
    })
    expect(originalTask.destroy).toHaveBeenCalledOnce()
    expect(copyTask.destroy).toHaveBeenCalledOnce()
  })

  it("reports rejected engine output without opening or downloading it", async () => {
    open.mockReturnValue(loading(Promise.resolve(documentWith())))
    convert.mockResolvedValue({ status: "transparency" })
    await expect(convertPdf(source, options())).resolves.toEqual({
      status: "transparency",
    })
    expect(open).toHaveBeenCalledOnce()
    expect(check).not.toHaveBeenCalled()
  })

  it("withholds an archive that lost original text or changed its geometry", async () => {
    open.mockReturnValue(loading(Promise.resolve(documentWith())))
    convert.mockResolvedValue({
      status: "ready",
      bytes: new ArrayBuffer(1),
      fontEncodingChanged: false,
    })
    check.mockResolvedValue("contentChanged")
    await expect(convertPdf(source, options())).resolves.toEqual({
      status: "contentChanged",
    })
  })

  it("reports an output the reader cannot open", async () => {
    open.mockReturnValueOnce(loading(Promise.resolve(documentWith())))
    open.mockImplementationOnce(() =>
      loading(Promise.reject(new Error("Invalid output")))
    )
    convert.mockResolvedValue({
      status: "ready",
      bytes: new ArrayBuffer(1),
      fontEncodingChanged: false,
    })
    await expect(convertPdf(source, options())).resolves.toEqual({
      status: "checkFailed",
    })
  })

  it("returns an error for password-protected input", async () => {
    open.mockImplementation(() =>
      loading(
        Promise.reject(
          Object.assign(new Error("Password required"), {
            name: "PasswordException",
          })
        )
      )
    )
    await expect(convertPdf(source, options())).resolves.toEqual({
      status: "encrypted",
    })
  })

  it("returns an error when the source PDF cannot be opened", async () => {
    open.mockImplementation(() =>
      loading(Promise.reject(new Error("Invalid input")))
    )
    await expect(convertPdf(source, options())).resolves.toEqual({
      status: "invalid",
    })
  })

  it("rejects an XFA-only form before starting the engine", async () => {
    open.mockReturnValue(
      loading(
        Promise.resolve(
          documentWith({
            IsXFAPresent: true,
            IsAcroFormPresent: false,
          })
        )
      )
    )
    await expect(convertPdf(source, options())).resolves.toEqual({
      status: "xfa",
    })
    expect(convert).not.toHaveBeenCalled()
  })

  it("cancels an outstanding read and releases the reader", async () => {
    const pending = loading(new Promise<never>(() => {}))
    open.mockReturnValue(pending)
    const controller = new AbortController()
    const conversion = convertPdf(source, {
      ...options(),
      signal: controller.signal,
    })
    await vi.waitFor(() => expect(open).toHaveBeenCalledOnce())
    controller.abort()
    await expect(conversion).rejects.toThrow("aborted")
    expect(pending.destroy).toHaveBeenCalledOnce()
  })
})
