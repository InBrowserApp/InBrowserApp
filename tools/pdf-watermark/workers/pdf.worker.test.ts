import { afterEach, expect, test, vi } from "vitest"
import { inspectPdf, watermarkPdf } from "../core/pdf"
import { DEFAULT_OPTIONS } from "../types"

vi.mock("../core/pdf", () => ({ inspectPdf: vi.fn(), watermarkPdf: vi.fn() }))
afterEach(() => vi.restoreAllMocks())

test("handles inspect/export messages and transfers generated bytes", async () => {
  const post = vi.spyOn(self, "postMessage").mockImplementation(() => {})
  const { handleRequest } = await import("./pdf.worker")
  vi.mocked(inspectPdf).mockResolvedValueOnce([])
  const request = { type: "inspect" as const, source: new ArrayBuffer(0) }
  expect(await handleRequest(request)).toEqual({ ok: true, pages: [] })
  vi.mocked(watermarkPdf).mockResolvedValue(new Uint8Array([1, 2]))
  const result = await handleRequest({
    type: "generate",
    source: request.source,
    layers: [{ png: request.source, options: DEFAULT_OPTIONS, pages: [1] }],
  })
  expect(result).toEqual({ ok: true, bytes: new Uint8Array([1, 2]) })
  self.dispatchEvent(
    new MessageEvent("message", {
      data: {
        type: "generate",
        source: request.source,
        layers: [{ png: request.source, options: DEFAULT_OPTIONS, pages: [1] }],
      },
    })
  )
  await vi.waitFor(() =>
    expect(post).toHaveBeenCalledWith(
      { ok: true, bytes: new Uint8Array([1, 2]) },
      { transfer: [expect.any(ArrayBuffer)] }
    )
  )
})

test("maps encryption, malformed document, and export failures to stable error codes", async () => {
  const { handleRequest } = await import("./pdf.worker")
  const source = new ArrayBuffer(0)
  vi.mocked(inspectPdf).mockRejectedValueOnce(new Error("encrypted PDF"))
  expect(await handleRequest({ type: "inspect", source })).toEqual({
    ok: false,
    error: "encryptedError",
  })
  vi.mocked(inspectPdf).mockRejectedValueOnce("unknown")
  expect(await handleRequest({ type: "inspect", source })).toEqual({
    ok: false,
    error: "readError",
  })
  vi.mocked(watermarkPdf).mockRejectedValueOnce(new Error("bad PDF"))
  expect(
    await handleRequest({
      type: "generate",
      source,
      layers: [{ png: source, options: DEFAULT_OPTIONS, pages: [1] }],
    })
  ).toEqual({ ok: false, error: "generateError" })
})
