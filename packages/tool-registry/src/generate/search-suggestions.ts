import type { ToolSearchIndexEntry } from "../types"

/** Emit standalone locale modules so the browser never imports the full index. */
export function createSearchSuggestionSources(
  entries: readonly ToolSearchIndexEntry[]
): Readonly<Record<string, string>> {
  const languages = [
    ...new Set([
      "en",
      ...entries.flatMap((entry) => Object.keys(entry.locales)),
    ]),
  ].sort()
  const sources: Record<string, string> = {}

  for (const language of languages) {
    const suggestions = entries.map((entry) => ({
      category: entry.category,
      name: (entry.locales[language] ?? entry.locales.en)!.name,
      slug: entry.slug,
    }))

    sources[`search-suggestions.${language}.ts`] = [
      "// Generated by pnpm tool-registry:generate. Do not edit.",
      `import type { ToolSearchSuggestionEntry } from "../types"`,
      "",
      `const entries: readonly ToolSearchSuggestionEntry[] = ${JSON.stringify(suggestions, null, 2)}`,
      "",
      "export default entries",
      "",
    ].join("\n")
  }

  sources["search-suggestions.ts"] = [
    "// Generated by pnpm tool-registry:generate. Do not edit.",
    `import type { ToolSearchSuggestionEntry } from "../types"`,
    "",
    "const loaders: Readonly<Record<string, () => Promise<{ default: readonly ToolSearchSuggestionEntry[] }>>> = {",
    ...languages.map(
      (language) =>
        `  "${language}": () => import("./search-suggestions.${language}"),`
    ),
    "}",
    "",
    "export async function loadToolSearchSuggestions(language: string) {",
    "  const load = loaders[language] ?? loaders.en!",
    "  return (await load()).default",
    "}",
    "",
  ].join("\n")

  return sources
}
